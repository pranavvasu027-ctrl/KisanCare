"""
Tests for DataReadinessGate & Provenance Verifier
=================================================
Verifies that:
1. Synthetic data is strictly blocked from serving as ground truth.
2. Cross-sectional data without multi-year paired re-tests is marked NOT_YET_VALIDATED.
3. Genuine longitudinal paired data passes the readiness gate.
4. Missing critical nutrients trigger gate blocks.
"""

import unittest
from ml.soil_intelligence.data_readiness import (
    DataReadinessGate,
    GateStatus,
    ProvenanceType,
    SamplingDesign
)


class TestDataReadinessGate(unittest.TestCase):

    def test_synthetic_data_rejection(self):
        """Synthetic datasets generated by numpy random functions must be blocked."""
        generator_snippet = "nitrogen = np.random.gamma(shape=4.0, scale=37.5, size=500)"
        rows = [
            {"plot_id": f"P{i}", "sample_date": "2024-01-01", "nitrogen": 150.0, "phosphorus": 15.0, "potassium": 250.0, "pH": 7.2}
            for i in range(50)
        ]
        columns = ["plot_id", "sample_date", "nitrogen", "phosphorus", "potassium", "pH"]

        report = DataReadinessGate.audit_tabular_records(
            file_path="mock_synthetic_batch.csv",
            rows=rows,
            columns=columns,
            declared_provenance=ProvenanceType.SYNTHETIC_GENERATED,
            generator_code=generator_snippet
        )

        self.assertTrue(report.is_synthetic)
        self.assertEqual(report.gate_status, GateStatus.BLOCKED)
        self.assertTrue(any("synthetic" in r.lower() for r in report.rejection_reasons))

    def test_cross_sectional_genuine_data_not_yet_validated(self):
        """
        Genuine cross-sectional data (like single-cycle SHC exports) contains
        real measurements but lacks longitudinal pairing across multiple years.
        It must be marked NOT_YET_VALIDATED for multi-year progression modeling.
        """
        # 100 genuine samples from 100 unique plots, sampled in a single cycle
        rows = [
            {
                "plot_id": f"MH_PLOT_{i:04d}",
                "sample_date": "2016-17",
                "nitrogen": 250.0 + (i % 50),
                "phosphorus": 12.0 + (i % 10),
                "potassium": 320.0 + (i % 80),
                "pH": 7.5
            }
            for i in range(100)
        ]
        columns = ["plot_id", "sample_date", "nitrogen", "phosphorus", "potassium", "pH"]

        report = DataReadinessGate.audit_tabular_records(
            file_path="raw_shc_export_cycle1.csv",
            rows=rows,
            columns=columns,
            declared_provenance=ProvenanceType.OFFICIAL_SHC_EXPORT
        )

        self.assertFalse(report.is_synthetic)
        self.assertFalse(report.has_longitudinal_pairs)
        self.assertEqual(report.sampling_design, SamplingDesign.CROSS_SECTIONAL)
        self.assertEqual(report.gate_status, GateStatus.NOT_YET_VALIDATED)
        self.assertTrue(any("longitudinal" in r.lower() for r in report.rejection_reasons))

    def test_longitudinal_paired_genuine_data_passed(self):
        """
        Genuine data with at least 10 plots measured at 2 or more distinct dates
        must pass the data-readiness gate.
        """
        rows = []
        for i in range(20):
            # Baseline test in 2023
            rows.append({
                "plot_id": f"FARM_FIELD_{i:02d}",
                "sample_date": "2023-05-15",
                "nitrogen": 220.0 + i,
                "phosphorus": 14.0 + (i % 5),
                "potassium": 280.0 + i * 2,
                "pH": 7.1
            })
            # Re-test in 2025
            rows.append({
                "plot_id": f"FARM_FIELD_{i:02d}",
                "sample_date": "2025-10-10",
                "nitrogen": 205.0 + i,
                "phosphorus": 16.0 + (i % 5),
                "potassium": 260.0 + i * 2,
                "pH": 7.0
            })

        columns = ["plot_id", "sample_date", "nitrogen", "phosphorus", "potassium", "pH"]

        report = DataReadinessGate.audit_tabular_records(
            file_path="paired_longitudinal_trials.csv",
            rows=rows,
            columns=columns,
            declared_provenance=ProvenanceType.RESEARCH_TRIAL
        )

        self.assertFalse(report.is_synthetic)
        self.assertTrue(report.has_longitudinal_pairs)
        self.assertEqual(report.sampling_design, SamplingDesign.LONGITUDINAL_PAIRED)
        self.assertEqual(report.gate_status, GateStatus.PASSED)
        self.assertEqual(len(report.rejection_reasons), 0)

    def test_missing_essential_nutrients_blocked(self):
        """Datasets missing Nitrogen, Phosphorus, or Potassium must be blocked."""
        rows = [{"plot_id": "P1", "sample_date": "2024-01-01", "nitrogen": 150.0, "pH": 7.0}]
        columns = ["plot_id", "sample_date", "nitrogen", "pH"]  # Missing phosphorus and potassium

        report = DataReadinessGate.audit_tabular_records(
            file_path="incomplete_test.csv",
            rows=rows,
            columns=columns,
            declared_provenance=ProvenanceType.CERTIFIED_LAB
        )

        self.assertEqual(report.gate_status, GateStatus.BLOCKED)
        self.assertFalse(report.has_phosphorus)
        self.assertFalse(report.has_potassium)


if __name__ == "__main__":
    unittest.main()
