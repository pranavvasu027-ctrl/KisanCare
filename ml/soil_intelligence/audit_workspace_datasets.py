"""
Workspace Dataset Audit Script for Soil Data
============================================
Scans the KISANcare workspace, evaluates all candidate soil datasets using
the DataReadinessGate, and documents their provenance, longitudinal readiness,
and synthetic status.
"""

import os
import csv
import json
from typing import List, Dict, Any
from ml.soil_intelligence.data_readiness import (
    DataReadinessGate,
    ProvenanceType,
    DatasetAuditReport,
    GateStatus
)


def audit_shc_raw_file(file_path: str) -> DatasetAuditReport:
    """Parses and audits the raw official SHC Maharashtra export."""
    if not os.path.exists(file_path):
        return DatasetAuditReport(
            file_path=file_path,
            row_count=0,
            column_count=0,
            provenance=ProvenanceType.UNKNOWN,
            sampling_design=None,
            is_synthetic=False,
            synthetic_markers=[],
            has_nitrogen=False,
            has_phosphorus=False,
            has_potassium=False,
            has_ph=False,
            has_sample_dates=False,
            has_plot_identifiers=False,
            has_longitudinal_pairs=False,
            gate_status=GateStatus.BLOCKED,
            rejection_reasons=["File not found"],
            actionable_recommendations=[]
        )

    rows = []
    columns = ['plot_id', 'sample_date', 'pH', 'nitrogen', 'phosphorus', 'potassium']

    with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
        reader = csv.reader(f)
        for line in reader:
            if len(line) > 2 and line[1].startswith('MH'):
                sample_no = line[1].strip()
                # Sample format: MH6092432/2016-17/33260557
                cycle = "2016-17" if "2016-17" in sample_no else "unknown"

                def parse_val(s):
                    if not s: return None
                    clean = "".join([c for c in s.split()[0] if c.isdigit() or c == '.'])
                    try:
                        return float(clean)
                    except ValueError:
                        return None

                ph = parse_val(line[2])
                n = parse_val(line[7])
                p = parse_val(line[8])
                k = parse_val(line[9])

                rows.append({
                    'plot_id': sample_no,
                    'sample_date': cycle,
                    'pH': ph,
                    'nitrogen': n,
                    'phosphorus': p,
                    'potassium': k
                })

    return DataReadinessGate.audit_tabular_records(
        file_path=file_path,
        rows=rows,
        columns=columns,
        declared_provenance=ProvenanceType.OFFICIAL_SHC_EXPORT
    )


def audit_synthetic_candidate(file_path: str, generator_script_path: str) -> DatasetAuditReport:
    """Audits the synthetic candidate generated by generate_synthetic_data.py."""
    generator_code = ""
    if os.path.exists(generator_script_path):
        with open(generator_script_path, 'r', encoding='utf-8', errors='ignore') as f:
            generator_code = f.read()

    rows = []
    columns = []

    if os.path.exists(file_path):
        with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
            reader = csv.DictReader(f)
            columns = reader.fieldnames or []
            for r in reader:
                rows.append(dict(r))

    return DataReadinessGate.audit_tabular_records(
        file_path=file_path,
        rows=rows,
        columns=columns,
        declared_provenance=ProvenanceType.SYNTHETIC_GENERATED,
        generator_code=generator_code
    )


def run_full_workspace_audit() -> List[DatasetAuditReport]:
    kisan_care_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    parent_kisancare_dir = os.path.abspath(os.path.join(kisan_care_root, ".."))

    # 1. SHC Raw dataset in unwanted imp files
    shc_raw_path = os.path.join(
        parent_kisancare_dir,
        "unwanted imp files",
        "ZIP",
        "KisancareP18",
        "Kisancare",
        "data",
        "npk",
        "raw",
        "raw_shc_maharashtra.csv"
    )
    shc_report = audit_shc_raw_file(shc_raw_path)

    # 2. Synthetic NPK training dataset
    synthetic_csv_path = os.path.join(
        parent_kisancare_dir,
        "unwanted imp files",
        "ZIP",
        "KisancareP18",
        "Kisancare",
        "data",
        "npk",
        "processed",
        "kisancare_npk_training.csv"
    )
    gen_script_path = os.path.join(
        parent_kisancare_dir,
        "unwanted imp files",
        "ZIP",
        "KisancareP18",
        "Kisancare",
        "scripts",
        "generate_synthetic_data.py"
    )
    synthetic_report = audit_synthetic_candidate(synthetic_csv_path, gen_script_path)

    return [shc_report, synthetic_report]


if __name__ == "__main__":
    reports = run_full_workspace_audit()
    for r in reports:
        print("=" * 60)
        print(f"File: {r.file_path}")
        print(f"Gate Status: {r.gate_status.value}")
        print(f"Is Synthetic: {r.is_synthetic}")
        print(f"Rows: {r.row_count}")
        print(f"Provenance: {r.provenance.value}")
        print(f"Sampling Design: {r.sampling_design.value if r.sampling_design else 'None'}")
        print(f"Rejection Reasons: {r.rejection_reasons}")
        print(f"Actionable Advice: {r.actionable_recommendations}")
